#!/usr/bin/env node
// Writes the room's catalogue into public/catalogue/ from the episodes chosen in tools/picks.js and
// what archive.org says about them, and it is committed (the page reads only this, never
// archive.org's search):
//   episodes.json      the episodes, as the page reads them (public/js/catalogue.js)
//   stills/<id>.jpg    a frame of each from its item's .thumbs (one a minute), on its tape and its set
//   captions/<id>.vtt  its captions, archive.org's speech to text, where the item has them (and its
//                      pick doesn't say they are no use)
// Each item is checked as the archive proxy checks it (worker.js refusal: in classic_tv or one of
// its decades, universal_newsreels or prelinger and marked public domain, or listed by name), and
// its video chosen: an mp4 that browsers play (h.264, or the upload itself), the one its captions
// were made from where there is one. Only the video itself is not copied: the page streams it from
// archive.org through the proxy.
//   node tools/catalogue.mjs [--only <id>]
// Run it again after changing tools/picks.js.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { PUBLIC } from './serve.mjs';
import { PICKS } from './picks.js';
import { refusal } from './archive-proxy/worker.js';

const ARCHIVE = 'https://archive.org';
const OUT = join(PUBLIC, 'catalogue');
/** Where along an episode its still is taken, unless its pick says: past the titles, into the story. */
const STILL_AT = 0.3;
/** The video formats browsers play, best first ("512Kb MPEG4" is MPEG-4 Part 2, which they don't). */
const FORMATS = ['h.264', 'h.264 IA', 'MPEG4'];

const { values } = parseArgs({ options: { only: { type: 'string' } } });

/** A file's base: its name without the extension, nor archive.org's `.ia` for its own encodes. */
const base = (name) => name.replace(/\.[^.]+$/, '').replace(/\.ia$/, '');

/** archive.org's `length`: seconds ("1561.23"), or "mm:ss" or "h:mm:ss". */
export function seconds(length) {
  const s = String(length ?? '');
  if (/^\d+(\.\d+)?$/.test(s)) return Number(s);
  const parts = s.split(':').map(Number);
  return parts.every((n) => Number.isFinite(n)) && parts.length > 1 ? parts.reduce((t, n) => t * 60 + n, 0) : 0;
}

/**
 * The video to play from an item's files, and its captions: by the pick's `file` if it names one,
 * else the best of FORMATS, from those with captions first. A video's captions are its own, else
 * its 512Kb copy's (the same video, so the same times: all that older items such as the newsreels
 * have). A named file (one of an item's several episodes) has only those; else the item's will do.
 * @param {{ name: string, format?: string, width?: string, length?: string }[]} files
 * @param {string} [named]
 */
export function chooseFiles(files, named) {
  const vtts = files.filter((f) => /\.autogenerated\.vtt$/.test(f.name));
  const of = (vtt) => base(vtt.name).replace(/\.autogenerated$/, '');
  const captions = vtts.filter((f) => !/_512kb\./.test(f.name));
  const captioned = (f) => captions.find((c) => of(c) === base(f.name)) ?? vtts.find((c) => of(c) === `${base(f.name)}_512kb`);
  const videos = files.filter((f) => /\.mp4$/i.test(f.name) && FORMATS.includes(f.format) && !f.name.includes('/'));
  const rank = (f) => (captioned(f) ? 0 : 10) + FORMATS.indexOf(f.format);
  const video = named ? files.find((f) => f.name === named) : [...videos].sort((a, b) => rank(a) - rank(b) || Number(b.width ?? 0) - Number(a.width ?? 0))[0];
  if (!video) return null;
  return { video, captions: captioned(video) ?? (named ? null : captions[0] ?? null) };
}

async function get(url, type = 'json') {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return type === 'json' ? await res.json() : type === 'text' ? await res.text() : Buffer.from(await res.arrayBuffer());
    } catch (err) {
      if (attempt >= 3) throw new Error(`${url}: ${err.message}`);
      await new Promise((r) => setTimeout(r, 1000 * attempt));
    }
  }
}

async function catalogue(pick) {
  const item = await get(`${ARCHIVE}/metadata/${pick.id}`);
  const why = refusal(item.metadata);
  if (why) throw new Error(`${pick.id}: ${why}`);
  const chosen = chooseFiles(item.files ?? [], pick.file);
  if (!chosen) throw new Error(`${pick.id}: no video a browser plays`);
  const { video } = chosen;
  const captions = pick.captions === false ? null : chosen.captions;
  const length = seconds(video.length);
  // The still: the item's frame nearest STILL_AT of the way in. Its thumbs are named by the video
  // they are of and their second; for a named file (one of the item's several episodes), its own.
  const thumbs = (item.files ?? []).flatMap((f) => {
    const m = /\.thumbs\/(.*)_(\d+)\.jpg$/.exec(f.name);
    return m && (!pick.file || m[1] === base(video.name)) ? [{ name: f.name, at: Number(m[2]) }] : [];
  }).sort((a, b) => a.at - b.at);
  if (!thumbs.length) throw new Error(`${pick.id}: no stills`);
  const at = pick.still ?? length * STILL_AT;
  const still = thumbs.reduce((best, t) => (Math.abs(t.at - at) < Math.abs(best.at - at) ? t : best));
  writeFileSync(join(OUT, 'stills', `${pick.id}.jpg`), await get(`${ARCHIVE}/download/${pick.id}/${encodeURI(still.name)}`, 'bytes'));
  if (captions) writeFileSync(join(OUT, 'captions', `${pick.id}.vtt`), await get(`${ARCHIVE}/download/${pick.id}/${encodeURI(captions.name)}`, 'text'));
  console.log(`${pick.id}: ${video.name} [${video.format}] ${video.width}x${video.height}, ${Math.round(length / 60)} min, still at ${still.at} s${captions ? ', captions' : ''}`);
  return {
    id: pick.id,
    show: pick.show,
    title: pick.title,
    decade: pick.decade,
    year: pick.year ?? null,
    file: video.name,
    minutes: Math.round(length / 60),
    width: Number(video.width) || null,
    height: Number(video.height) || null,
    still: `catalogue/stills/${pick.id}.jpg`,
    captions: captions ? `catalogue/captions/${pick.id}.vtt` : null,
  };
}

const picks = values.only ? PICKS.filter((p) => p.id === values.only) : PICKS;
if (!values.only) rmSync(OUT, { recursive: true, force: true });
for (const dir of ['stills', 'captions']) mkdirSync(join(OUT, dir), { recursive: true });
const episodes = [];
for (let i = 0; i < picks.length; i += 4) episodes.push(...(await Promise.all(picks.slice(i, i + 4).map(catalogue))));
if (values.only) {
  console.log(JSON.stringify(episodes[0], null, 2));
} else {
  const json = { about: 'The episodes the room shows (tools/picks.js, written by tools/catalogue.mjs), from https://archive.org/details/classic_tv, https://archive.org/details/universal_newsreels, https://archive.org/details/prelinger and the films tools/archive-proxy/worker.js lists', episodes };
  writeFileSync(join(OUT, 'episodes.json'), `${JSON.stringify(json, null, 1)}\n`);
  console.log(`${episodes.length} episodes, ${readdirSync(join(OUT, 'captions')).length} with captions, into ${OUT}`);
}
