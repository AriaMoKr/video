// The archive proxy (tools/archive-proxy/worker.js): it relays parts of the video files of the
// room's picks (tools/picks.js), archive.org's public-domain classic TV, newsreels, cartoons and
// films, with CORS, for the pages of the sites only, and nothing else.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import worker, { ARCHIVE, LISTED, OWNERS, allowOrigin, handle, refusal } from '../tools/archive-proxy/worker.js';
import { PICKS } from '../tools/picks.js';

// A pick, Dragnet's "The Big Little Jesus" (1953), its file and its metadata as archive.org has them.
const FILE = 'https://proxy.example/download/TheBigLittleJesus/drag_ep064_12-24-53_The_Big_Little_Jesus.mp4';
const PD = { identifier: 'TheBigLittleJesus', collection: ['classic_tv_1950s', 'classic_tv', 'television'], licenseurl: 'http://creativecommons.org/licenses/publicdomain/' };
const LM = 'Sat, 21 Nov 2009 10:12:01 GMT';
const SITES = 'https://ariamokr.github.io, http://localhost:*, http://127.0.0.1:*';
const NOT_PICKED = "not one of the room's picks";

/** A fake archive.org: items' metadata by id, and what a download answers (a status, 'down' or a function). */
function archive({ items = { TheBigLittleJesus: PD }, download = 206 } = {}) {
  const asked = [];
  const fetch = async (url, init = {}) => {
    asked.push(url.replace(ARCHIVE, ''));
    const meta = /^https:\/\/archive\.org\/metadata\/([^/]+)\/metadata$/.exec(url);
    if (meta) return Response.json(items[meta[1]] ? { result: items[meta[1]] } : {});
    if (download === 'down') throw new TypeError('fetch failed');
    if (typeof download === 'function') return download(url, init);
    if (download === 206) {
      return new Response('abcd', { status: 206, headers: { 'content-range': 'bytes 0-3/161000000', 'content-length': '4', 'content-type': 'video/mp4', 'last-modified': LM, 'x-other': 'no' } });
    }
    return new Response('nope', { status: download });
  };
  return { fetch, asked };
}

const get = (url, headers = {}, method = 'GET') => new Request(url, { method, headers });

test('it answers a preflight, and refuses what is not a part of a video file of an item', async () => {
  const { fetch, asked } = archive();
  const pre = await handle(get(FILE, {}, 'OPTIONS'), { fetch, items: new Map() });
  assert.equal(pre.status, 204);
  assert.equal(pre.headers.get('access-control-allow-origin'), '*');
  assert.match(pre.headers.get('access-control-allow-headers'), /Range/);
  const status = async (req) => (await handle(req, { fetch, items: new Map() })).status;
  assert.equal(await status(get(FILE)), 416, 'no Range: a video always sends one');
  assert.equal(await status(get(FILE, { range: 'bytes=9-3' })), 416);
  assert.equal(await status(get(FILE, { range: 'bytes=-500' })), 416, 'the end of the file: not how a video asks');
  for (const path of ['/download/TheBigLittleJesus/drag_ep064_12-24-53_The_Big_Little_Jesus.autogenerated.vtt', '/download/TheBigLittleJesus/a/b.mp4',
    '/download/../metadata/x.mp4', '/details/TheBigLittleJesus', '/download/TheBigLittleJesus/', '/download/a%2Fb/c.mp4']) {
    assert.equal(await status(get(`https://proxy.example${path}`, { range: 'bytes=0-' })), 404, path);
  }
  assert.equal(await status(new Request(FILE, { method: 'POST', body: 'x' })), 405);
  assert.equal(asked.length, 0, 'archive.org was not asked');
  const refused = await handle(get(FILE), { fetch, items: new Map() });
  assert.equal(refused.headers.get('access-control-allow-origin'), '*', 'a page can read why');
});

test("it relays the room's picks and nothing else, whatever archive.org marks an item", async () => {
  // Bonanza's "Death on Sun Mountain" (1959), marked CC0 in classic_tv though NBC renewed it in 1987,
  // and the California Academy of Sciences' "Science in Action: Polynesian Culture" (1959), its
  // owner's under CC BY-NC-ND 4.0, as archive.org has them: the marks would pass on a pick, but
  // neither is one.
  const BONANZA = { identifier: 'Bonanza-DeathOnSunMountain', collection: ['classic_tv_1950s', 'classic_tv', 'television'], licenseurl: 'http://creativecommons.org/publicdomain/zero/1.0/' };
  const POLYNESIAN = { identifier: 'rar_sia360_polynesian_culture_202204', collection: ['calacademyvideo', 'americana', 'stream_only', 'californiarevealed'], licenseurl: 'http://creativecommons.org/licenses/by-nc-nd/4.0/' };
  for (const md of [BONANZA, POLYNESIAN]) {
    assert.ok(!PICKS.some((p) => p.id === md.identifier), md.identifier);
    assert.equal(refusal(md), NOT_PICKED, md.identifier);
    assert.equal(refusal({ ...md, identifier: PD.identifier }), null, `${md.identifier}'s marks, on a pick`);
  }
  // Asked for from the room's page, they are refused before archive.org is asked; a pick is relayed.
  const { fetch, asked } = archive({ items: { [BONANZA.identifier]: BONANZA, [POLYNESIAN.identifier]: POLYNESIAN, TheBigLittleJesus: PD } });
  const as = (path) => handle(get(`https://proxy.example${path}`, { range: 'bytes=0-', origin: 'https://ariamokr.github.io' }), { fetch, items: new Map(), origins: SITES });
  for (const path of ['/download/Bonanza-DeathOnSunMountain/BonanzaS1e02DeathOnSunMountain.mp4', '/download/rar_sia360_polynesian_culture_202204/rar_sia360_polynesian_culture_access.HD.mp4']) {
    const res = await as(path);
    assert.equal(res.status, 403, path);
    assert.equal(await res.text(), `${path.split('/')[2]}: ${NOT_PICKED}\n`);
    // However it is asked for: with no Range, or a HEAD.
    for (const [headers, method] of [[{}, 'GET'], [{ range: 'bytes=0-' }, 'HEAD']]) {
      const other = await handle(get(`https://proxy.example${path}`, { ...headers, origin: 'https://ariamokr.github.io' }, method), { fetch, items: new Map(), origins: SITES });
      assert.equal(other.status, 403, `${method} ${path}`);
    }
  }
  assert.deepEqual(asked, []);
  assert.equal((await as(new URL(FILE).pathname)).status, 206);
  assert.deepEqual(asked, ['/metadata/TheBigLittleJesus/metadata', new URL(FILE).pathname]);
  // Every pick is one wherever it is, and nothing else: another copy of a listed film is not.
  for (const p of PICKS) assert.equal(refusal({ identifier: p.id, collection: ['classic_tv'], licenseurl: PD.licenseurl }), null, p.id);
  assert.equal(refusal({ identifier: 'SteamboatBillJr_2014', collection: ['silenthalloffame'] }), NOT_PICKED);
  assert.equal(refusal({ identifier: '2306_Design_for_Dreaming_21_26_14_00', collection: ['prelinger'] }), NOT_PICKED, "a newer copy of a Prelinger pick's film");
  assert.equal(refusal({ collection: ['classic_tv'], licenseurl: PD.licenseurl }), NOT_PICKED, 'no identifier');
});

test("a pick must also be in classic_tv or one of its decades, universal_newsreels or prelinger and marked public domain, listed, or an owner's film under Creative Commons", async () => {
  const OTHER = "not in classic_tv, universal_newsreels, prelinger or an owner's collection, nor listed";
  /** The metadata of a pick (any will do: its id is looked at first, then the rest). */
  const pick = (md) => ({ identifier: PD.identifier, ...md });
  assert.equal(refusal(PD), null);
  assert.equal(refusal(pick({ collection: 'classic_tv', licenseurl: 'http://creativecommons.org/publicdomain/mark/1.0/' })), null);
  assert.equal(refusal(pick({ collection: ['classic_tv_1970s'], licenseurl: 'https://creativecommons.org/publicdomain/zero/1.0/' })), null);
  assert.equal(refusal({ identifier: '1958-02-03_First_US_Satellite_Launched', collection: ['universal_newsreels', 'newsandpublicaffairs'], licenseurl: PD.licenseurl }), null, 'a newsreel');
  assert.equal(refusal({ identifier: 'Designfo1956', collection: ['prelinger'], licenseurl: PD.licenseurl }), null, "Prelinger's own copy");
  assert.equal(refusal(pick({ collection: ['classic_tv'] })), 'not marked public domain', 'no licence, as Bonanza_-_The_Trail_Gang has');
  assert.equal(refusal(pick({ collection: ['universal_newsreels'] })), 'not marked public domain', 'the few newsreels not marked');
  assert.equal(refusal(pick({ collection: ['prelinger'] })), 'not marked public domain', "the Prelinger's newer copies");
  assert.equal(refusal(pick({ collection: ['classic_tv'], licenseurl: 'http://creativecommons.org/licenses/by-nc/3.0/' })), 'not marked public domain');
  for (const other of ['feature_films', 'classic_tv_commercials', 'newsandpublicaffairs', 'universal_newsreels_extra', 'prelingerhomemovies']) {
    assert.equal(refusal(pick({ collection: [other], licenseurl: PD.licenseurl })), OTHER, other);
  }
  // A listed item, wherever it is and marked or not; each listed one a pick, or the listing is no use.
  assert.ok(LISTED.size > 0);
  for (const id of LISTED.keys()) {
    assert.ok(PICKS.some((p) => p.id === id), `${id} is listed but not a pick`);
    assert.equal(refusal({ identifier: id, collection: ['silenthalloffame'] }), null, id);
  }
  assert.equal(refusal(pick({ collection: ['opensource_movies'], licenseurl: PD.licenseurl })), OTHER, 'marked, but neither in those nor listed');
  // An owner's own films (no pick yet), under any of Creative Commons' six licences (or marked public domain).
  assert.equal(OWNERS.get('calacademyvideo'), 'California Academy of Sciences');
  for (const licenseurl of ['http://creativecommons.org/licenses/by-nc-nd/4.0/', 'https://creativecommons.org/licenses/by/4.0/', 'http://creativecommons.org/licenses/by-nc-sa/3.0/us/', 'http://creativecommons.org/licenses/by-sa/2.0', 'http://creativecommons.org/licenses/by-nd/2.5/', PD.licenseurl]) {
    assert.equal(refusal(pick({ collection: ['calacademyvideo'], licenseurl })), null, `Science in Action: ${licenseurl}`);
  }
  const UNLICENSED = 'not under a Creative Commons licence, nor marked public domain';
  assert.equal(refusal(pick({ collection: ['calacademyvideo'] })), UNLICENSED, 'unmarked, as many of its films are');
  for (const licenseurl of ['http://creativecommons.org/licenses/sampling+/1.0/', 'https://example.org/licenses/by/4.0/']) {
    assert.equal(refusal(pick({ collection: ['calacademyvideo'], licenseurl })), UNLICENSED, licenseurl);
  }
  // Anyone else's licence isn't trusted: an uploader's, on someone else's film.
  assert.equal(refusal(pick({ collection: ['opensource_movies'], licenseurl: 'http://creativecommons.org/licenses/by-nc-nd/3.0/' })), OTHER);
  assert.equal(refusal(pick({ collection: ['classic_tv'], licenseurl: 'https://creativecommons.org/licenses/by/4.0/' })), 'not marked public domain');
  assert.equal(refusal(undefined), 'no such item');
  // Through the proxy: a pick no longer marked, or gone from archive.org, is refused, and no file asked for.
  const { fetch, asked } = archive({ items: { TheBigLittleJesus: pick({ collection: ['classic_tv'] }) } });
  const items = new Map();
  const res = await handle(get(FILE, { range: 'bytes=0-' }), { fetch, items });
  assert.equal(res.status, 403);
  assert.match(await res.text(), /not marked public domain/);
  assert.equal((await handle(get('https://proxy.example/download/Life_with_Elizabeth/x.mp4', { range: 'bytes=0-' }), { fetch, items })).status, 403);
  assert.deepEqual(asked, ['/metadata/TheBigLittleJesus/metadata', '/metadata/Life_with_Elizabeth/metadata'], 'no file was asked for');
});

test('it relays the part with CORS headers, asking about an item once for a while', async () => {
  const { fetch, asked } = archive();
  const items = new Map();
  const res = await handle(get(FILE, { range: 'bytes=0-' }), { fetch, items });
  assert.equal(res.status, 206);
  assert.equal(await res.text(), 'abcd');
  assert.equal(res.headers.get('content-range'), 'bytes 0-3/161000000');
  assert.equal(res.headers.get('content-type'), 'video/mp4');
  assert.equal(res.headers.get('last-modified'), LM);
  assert.equal(res.headers.get('access-control-allow-origin'), '*');
  assert.match(res.headers.get('access-control-expose-headers'), /Content-Range.*Content-Length.*Accept-Ranges/);
  assert.equal(res.headers.get('x-other'), null, 'only what a video needs');
  // The next part, a seek, goes straight to the file; an hour later the item is asked about again.
  await handle(get(FILE, { range: 'bytes=80000000-' }), { fetch, items });
  await handle(get(FILE, { range: 'bytes=0-' }), { fetch, items, now: () => Date.now() + 2 * 3600e3 });
  const file = new URL(FILE).pathname;
  assert.deepEqual(asked, ['/metadata/TheBigLittleJesus/metadata', file, file, '/metadata/TheBigLittleJesus/metadata', file]);
  // The Range goes on to archive.org as it came, and a name with spaces as the page wrote it.
  let sent = null;
  const LR = 'the-lone-ranger-1949-s-01-e-02-the-lone-ranger-fights-on';
  const spaced = archive({ items: { [LR]: { ...PD, identifier: LR } }, download: (url, init) => {
    sent = { url, range: init.headers.range };
    return new Response(null, { status: 206 });
  } });
  await handle(get(`https://proxy.example/download/${LR}/The%20Lone%20Ranger%20(S01E02).mp4`, { range: 'bytes=500-999' }), { fetch: spaced.fetch, items: new Map() });
  assert.deepEqual(sent, { url: `${ARCHIVE}/download/${LR}/The%20Lone%20Ranger%20(S01E02).mp4`, range: 'bytes=500-999' });
  // A HEAD: the headers alone.
  const head = await handle(get(FILE, { range: 'bytes=0-' }, 'HEAD'), { fetch, items });
  assert.equal(head.status, 206);
  assert.equal(head.body, null);
});

test('what archive.org answers otherwise is said, not relayed', async () => {
  let cancelled = 0;
  const failing = () => new Response(new ReadableStream({ pull: (c) => c.enqueue(new Uint8Array(64)), cancel: () => { cancelled++; } }), { status: 503 });
  const status = async (download) => {
    const res = await handle(get(FILE, { range: 'bytes=0-' }), { fetch: archive({ download }).fetch, items: new Map() });
    assert.equal(res.headers.get('access-control-allow-origin'), '*');
    return res.status;
  };
  assert.equal(await status(404), 404);
  assert.equal(await status(failing), 502);
  assert.equal(cancelled, 1, 'the error page was not read');
  assert.equal(await status('down'), 502);
  // Past the end of the file: archive.org's 416 says how long it is, which the video needs.
  const past = await handle(get(FILE, { range: 'bytes=999999999-' }), {
    fetch: archive({ download: () => new Response('', { status: 416, headers: { 'content-range': 'bytes */161000000' } }) }).fetch, items: new Map(),
  });
  assert.equal(past.status, 416);
  assert.equal(past.headers.get('content-range'), 'bytes */161000000');
  // archive.org's metadata failing is not held against the item.
  const items = new Map();
  const down = async () => { throw new TypeError('fetch failed'); };
  assert.equal((await handle(get(FILE, { range: 'bytes=0-' }), { fetch: down, items })).status, 502);
  assert.equal(items.size, 0);
});

test('it serves only the pages of its own sites (ALLOWED_ORIGINS), so no other can spend its requests', async () => {
  assert.equal(allowOrigin('https://ariamokr.github.io', SITES), 'https://ariamokr.github.io');
  assert.equal(allowOrigin('http://localhost:8098', SITES), 'http://localhost:8098', 'any port');
  assert.equal(allowOrigin('http://127.0.0.1:8098', SITES), 'http://127.0.0.1:8098');
  assert.equal(allowOrigin('https://other.github.io', SITES), null);
  assert.equal(allowOrigin('https://ariamokr.github.io.evil.example', SITES), null);
  assert.equal(allowOrigin('http://localhost.evil.example:80', SITES), null);
  assert.equal(allowOrigin(null, SITES), null, 'no Origin: not a page');
  const { fetch, asked } = archive();
  const as = (origin) => handle(get(FILE, { range: 'bytes=0-', ...(origin ? { origin } : {}) }), { fetch, items: new Map(), origins: SITES });
  const refused = await as('https://other.example');
  assert.equal(refused.status, 403);
  assert.equal(refused.headers.get('access-control-allow-origin'), null);
  assert.equal((await as(null)).status, 403);
  assert.equal(asked.length, 0);
  const ok = await as('https://ariamokr.github.io');
  assert.equal(ok.status, 206);
  assert.equal(ok.headers.get('access-control-allow-origin'), 'https://ariamokr.github.io');
  assert.equal(ok.headers.get('vary'), 'Origin');
  // The deployed Worker takes the list from its environment (wrangler.toml [vars]).
  const toml = readFileSync(new URL('../tools/archive-proxy/wrangler.toml', import.meta.url), 'utf8');
  assert.match(toml, /^name = "video-archive-proxy"$/m);
  const listed = /^ALLOWED_ORIGINS = "([^"]+)"$/m.exec(toml)?.[1];
  assert.ok(listed && allowOrigin('https://ariamokr.github.io', listed) && !allowOrigin('https://other.example', listed), listed);
  const quiet = console.log; // the Worker logs each request (below, what)
  console.log = () => {};
  try {
    assert.equal((await worker.fetch(get(FILE, { range: 'bytes=0-', origin: 'https://other.example' }), { ALLOWED_ORIGINS: listed })).status, 403);
  } finally {
    console.log = quiet;
  }
});

test('each request is logged as one entry, with nothing about the visitor but the continent', async () => {
  const entries = [];
  const { fetch } = archive();
  await handle(get(FILE, { range: 'bytes=1000-', origin: 'https://ariamokr.github.io', 'user-agent': 'Quest', 'cf-connecting-ip': '203.0.113.9' }),
    { fetch, items: new Map(), continent: 'NA', log: (e) => entries.push(e) });
  await handle(get(FILE, { origin: 'https://ariamokr.github.io' }), { fetch, items: new Map(), log: (e) => entries.push(e) });
  assert.equal(entries.length, 2);
  const [ok, refused] = entries;
  assert.deepEqual(Object.keys(ok).sort(), ['continent', 'file', 'from', 'item', 'method', 'ms', 'origin', 'status']);
  assert.equal(ok.item, 'TheBigLittleJesus');
  assert.equal(ok.file, 'drag_ep064_12-24-53_The_Big_Little_Jesus.mp4');
  assert.equal(ok.from, 1000);
  assert.equal(ok.continent, 'NA');
  assert.equal(ok.status, 206);
  assert.equal(refused.refused, 'range');
  assert.ok(!JSON.stringify(entries).includes('203.0.113.9') && !JSON.stringify(entries).includes('Quest'));
});
